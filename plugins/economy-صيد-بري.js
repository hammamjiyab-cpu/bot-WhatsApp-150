let handler = async (m, { conn, usedPrefix, command }) => {

    
    if (m.isGroup && !global.db.data.chats[m.chat]?.economy) {
        return m.reply(`《✦》أوامر *الاقتصاد* متعطلة في المجموعة ❌

👮‍♂️ ممكن *حد من الأدمنز* يفعلها بالأمر ده:
» *${usedPrefix}economy on* ✅`)
    }

    
    let user = global.db.data.users[m.sender]

    if (!user) {
        user = global.db.data.users[m.sender] = {
            exp: 0,
            coin: 0,
            health: 100,
            lastHunt: 0
        }
    }

    
    if (typeof user.coin !== 'number') user.coin = 0
    if (typeof user.exp !== 'number') user.exp = 0
    if (typeof user.health !== 'number') user.health = 100
    if (typeof user.lastHunt !== 'number') user.lastHunt = 0

    
    if (user.health < 5) {
        return conn.reply(
            m.chat,
            `ꕥ معندكش صحة كفاية عشان ترجع *تصطاد* 🦌

> استخدم *${usedPrefix}عالج* عشان تتعالج ❤️‍🩹`,
            m
        )
    }

    
    const cooldown = 15 * 60 * 1000
    const now = Date.now()

    if (now < user.lastHunt) {
        const remaining = user.lastHunt - now

        return conn.reply(
            m.chat,
            `ꕥ لازم تستنى *${formatTime(remaining)}* قبل ما تستخدم *${usedPrefix + command}* تاني ⏳`,
            m
        )
    }

    
    user.lastHunt = now + cooldown

    const evento = pickRandom(eventos)

    let monedas
    let experiencia
    let salud

    
    if (evento.tipo === 'انتصار') {

        monedas = Math.floor(Math.random() * 10001) + 1000
        experiencia = Math.floor(Math.random() * 91) + 30
        salud = Math.floor(Math.random() * 5) + 3

        user.coin += monedas
        user.exp += experiencia
        user.health -= salud

    } 
    
    
    else {

        monedas = Math.floor(Math.random() * 2001) + 4000
        experiencia = Math.floor(Math.random() * 41) + 30
        salud = Math.floor(Math.random() * 5) + 3

        user.coin -= monedas
        user.exp -= experiencia
        user.health -= salud

        if (user.coin < 0) user.coin = 0
        if (user.exp < 0) user.exp = 0
    }

    
    if (user.health < 0) user.health = 0

    
    if (global.db.write) {
        await global.db.write()
    }

    
    const result = `❀ ${evento.mensaje}

╭─〔 🏹 الصيد البري 〕
│ 💰 المبلغ: *¥${monedas.toLocaleString()} ${currency}*
│ ⭐ الخبرة: *${experiencia} XP*
│ ❤️ الصحة: *${user.health}/100*
╰──────────────`

    await conn.reply(m.chat, result, m)
}

handler.help = ['صيد-بري']
handler.tags = ['economy']
handler.command = ['صيد-بري', 'hunt']
handler.group = true

export default handler






function formatTime(ms) {
    const totalSec = Math.ceil(ms / 1000)
    const min = Math.floor(totalSec / 60)
    const sec = totalSec % 60

    const parts = []

    if (min > 0) {
        parts.push(`${min} دقيقة`)
    }

    if (sec > 0 || min === 0) {
        parts.push(`${sec} ثانية`)
    }

    return parts.join(' و ')
}

function pickRandom(list) {
    return list[Math.floor(Math.random() * list.length)]
}






